  /* Load stack address */
  la x2, stack_end
  /* Load parameters */
  la x10, signature
  la x11, message
  la x12, messagelen
  lw x12, 0(x12) /* msglen */
  la x13, sk
  /* Prepare context */
  la x14, ctx
  li x15, CTXLEN

  jal x1, sign_dilithium

