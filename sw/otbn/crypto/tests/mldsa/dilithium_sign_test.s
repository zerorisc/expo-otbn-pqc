.globl main
main:
  /* Init all-zero register. */
  bn.xor  w31, w31, w31
  
  /* MOD <= dmem[modulus] = DILITHIUM_Q */
  li      x5, 2
  la      x6, modulus
  bn.lid  x5, 0(x6)

  /* MOD 2nd word <= DILITHIUM_R */
  li      x5, 3
  la      x6, montg_R
  bn.lid  x5, 0(x6)
  bn.rshi w2, w3, w2 >> 224
  /* Write back MOD */
  bn.wsrw 0x0, w2

  /* Load stack address */
  la x2, stack_end
  /* Load parameters */
  la x10, signature
  la x11, message
  la x12, messagelen
  lw x12, 0(x12) /* msglen */
  la x13, sk
  /* Prepare context */
  la x14, ctx
  li x15, CTXLEN

  jal x1, sign_dilithium

#if DILITHIUM_MODE == 3
  li   x10, CRYPTO_BYTES
  addi x10, x10, -1
  la   x11, signature
  add  x11, x11, x10
  lw   x10, 0(x11)
  slli x10, x10, 24
  srli x10, x10, 24
  sw   x10, 0(x11)
